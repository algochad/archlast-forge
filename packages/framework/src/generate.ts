import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RouteFile, RouteTree } from "./routes";

/** Import specifier, from .forge/gen, for a file in app/. */
const specifier = (file: string) => `../../app/${file.replace(/\.(tsx|ts|jsx|js)$/, "")}`;

function render(routes: RouteFile[], mode: "client" | "server", imports: string[], indent: string): string {
  return `[${routes
    .map((r) => {
      const fields = [`id: ${JSON.stringify(r.id)}`];
      if (r.path !== undefined) fields.push(`path: ${JSON.stringify(r.path)}`);
      if (r.index) fields.push("index: true");
      if (mode === "client") fields.push(`load: () => import(${JSON.stringify(specifier(r.file))})`);
      else {
        const name = `route${imports.length}`;
        imports.push(`import * as ${name} from ${JSON.stringify(specifier(r.file))};`);
        fields.push(`module: ${name}`);
      }
      if (r.children) fields.push(`children: ${render(r.children, mode, imports, indent + "  ")}`);
      return `\n${indent}  { ${fields.join(", ")} }`;
    })
    .join(",")}\n${indent}]`;
}

function manifestSource(tree: RouteTree, mode: "client" | "server"): string {
  const imports: string[] = [];
  const rootImport = tree.root ? `import * as root from ${JSON.stringify(specifier(tree.root))};` : "const root = {};";
  const children = render(tree.routes, mode, imports, "  ");
  return `// Generated by archlast-forge from app/. Don't edit; it is rewritten on every build.
import type { ManifestNode } from "@archlast/forge-framework/client";
${rootImport}
${imports.join("\n")}

export const manifest: ManifestNode = { id: "root", module: root, children: ${children} };
${mode === "server" ? 'export { templates } from "./render.server";' : ""}
`;
}

/** Writes the generated sources into <root>/.forge/gen and returns their directory. */
export function generate(root: string, tree: RouteTree): string {
  const dir = join(root, ".forge", "gen");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "routes.client.ts"), manifestSource(tree, "client"));
  writeFileSync(join(dir, "routes.server.ts"), manifestSource(tree, "server"));
  writeFileSync(
    join(dir, "entry.client.tsx"),
    `// Generated by archlast-forge. Don't edit.
import { startClient } from "@archlast/forge-framework/client";
import { manifest } from "./routes.client";

startClient(manifest);
`,
  );
  return dir;
}
