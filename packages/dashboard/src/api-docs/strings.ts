export type StringKey = keyof typeof STRING_KEYS;
export type Translate = (key: StringKey, values?: Record<string, string | number>) => string;

/** `t(key, values)`: the app's text for the key, else English, with `{name}` filled in. */
export function makeTranslate(overrides?: Record<string, string>): Translate {
  return (key, values) => {
    const text = overrides?.[key] ?? STRING_KEYS[key];
    return values ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in values ? String(values[name]) : m)) : text;
  };
}
