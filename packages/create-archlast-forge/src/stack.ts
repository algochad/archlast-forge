/** compose.yaml: the app and the services it was asked to run, wired together. */
export function renderCompose({ name, services, version }: { name: string; services: StackService[]; version: string }): string {
  const has = (s: StackService) => services.includes(s);
  const proxied = has("caddy");
  const env: string[] = [
    "BETTER_AUTH_SECRET: ${BETTER_AUTH_SECRET:?missing: run `archlast-forge up`, which creates .env}",
    "ADMIN_KEY: ${ADMIN_KEY:?missing: run `archlast-forge up`, which creates .env}",
    "BETTER_AUTH_URL: ${BETTER_AUTH_URL:-http://localhost:3000}",
    "ALLOW_INSECURE_HTTP: ${ALLOW_INSECURE_HTTP:-}",
    "DASHBOARD: ${DASHBOARD:-on}",
    "OTEL_SERVICE_NAME: ${OTEL_SERVICE_NAME:-}", // this app's name on the dashboard, and in its Redis keys; empty is no name
  ];
  if (proxied) env.push("TRUST_PROXY: \"1\"", "TRUSTED_ORIGINS: https://${DOMAIN}");
  if (has("postgres")) env.push("DATABASE_URL: postgres://forge:${POSTGRES_PASSWORD}@postgres:5432/forge");
  if (has("redis")) env.push("REDIS_URL: redis://redis:6379", "REDIS_PREFIX: ${REDIS_PREFIX:-}");
  if (has("s3"))
    env.push("S3_ENDPOINT: http://rustfs:9000", "S3_PUBLIC_ENDPOINT: ${S3_PUBLIC_ENDPOINT}", "S3_BUCKET: forge", "S3_REGION: us-east-1", "S3_ACCESS_KEY_ID: ${S3_ACCESS_KEY}", "S3_SECRET_ACCESS_KEY: ${S3_SECRET_KEY}");

  // Quoted: the "missing" messages contain ": ", which YAML would take for a new key. Compose still expands ${...} inside quotes.
  const quoted = (e: string) => `      ${e.slice(0, e.indexOf(": "))}: "${e.slice(e.indexOf(": ") + 2).replace(/^"|"$/g, "")}"`;

  const deps: string[] = [];
  if (has("postgres")) deps.push("      postgres:\n        condition: service_healthy");
  if (has("redis")) deps.push("      redis:\n        condition: service_healthy");
  if (has("s3")) deps.push("      rustfs-init:\n        condition: service_completed_successfully");

  const parts: string[] = [];
  parts.push(`# The production stack for ${name}. \`archlast-forge up\` builds and starts it; \`archlast-forge down\` stops it.
# This file is yours: edit it, and archlast-forge will run what you wrote.
name: ${name}

services:
  app:
    build:
      context: .
      args:
        ENGINE_IMAGE: \${ENGINE_IMAGE:-${engineImageFor(version)}}
    image: ${name}:latest
    restart: unless-stopped
${proxied ? "" : `    ports:\n      - "\${PORT:-3000}:3000"\n`}    environment:
${env.map(quoted).join("\n")}
    volumes:
      - app-data:/data${deps.length ? `\n    depends_on:\n${deps.join("\n")}` : ""}`);

  if (has("postgres"))
    parts.push(`  postgres:
    image: postgres:17-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: forge
      POSTGRES_PASSWORD: "\${POSTGRES_PASSWORD:?missing: run \`archlast-forge up\`, which creates .env}"
      POSTGRES_DB: forge
    volumes:
      - postgres-data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U forge -d forge"]
      interval: 3s
      timeout: 3s
      retries: 20`);

  if (has("redis"))
    parts.push(`  redis:
    image: redis:7-alpine
    restart: unless-stopped
    command: ["redis-server", "--appendonly", "yes"]
    volumes:
      - redis-data:/data
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 3s
      timeout: 3s
      retries: 20`);

  if (has("s3"))
    parts.push(`  rustfs:
    image: rustfs/rustfs:1.0.4
    restart: unless-stopped
    command: ["/data"]
    environment:
      RUSTFS_ACCESS_KEY: "\${S3_ACCESS_KEY:?missing: run \`archlast-forge up\`, which creates .env}"
      RUSTFS_SECRET_KEY: "\${S3_SECRET_KEY:?missing: run \`archlast-forge up\`, which creates .env}"
      # Only the app's pages may upload and download from a browser.
      RUSTFS_CORS_ALLOWED_ORIGINS: "${proxied ? "https://\${DOMAIN:-localhost}" : "\${BETTER_AUTH_URL:-http://localhost:\${PORT:-3000}}"}"
${proxied ? "" : `    ports:\n      - "\${S3_PORT:-9000}:9000"   # browsers upload and download here, through presigned URLs\n`}    volumes:
      - rustfs-data:/data

  # Creates the bucket once, then exits.
  rustfs-init:
    image: amazon/aws-cli:2.39.3
    depends_on:
      - rustfs
    restart: "no"
    environment:
      AWS_ACCESS_KEY_ID: \${S3_ACCESS_KEY}
      AWS_SECRET_ACCESS_KEY: \${S3_SECRET_KEY}
      AWS_DEFAULT_REGION: us-east-1
    entrypoint:
      - sh
      - -c
      - |
        for i in $$(seq 1 60); do
          out=$$(aws --endpoint-url http://rustfs:9000 s3 mb s3://forge 2>&1) && exit 0
          echo "$$out" | grep -q BucketAlready && exit 0
          sleep 1
        done
        echo "$$out"; exit 1`);

  if (proxied)
    parts.push(`  caddy:
    image: caddy:2-alpine
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    environment:
      DOMAIN: \${DOMAIN:-localhost}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config
    depends_on:
      - app`);

  const volumes = ["app-data", ...(has("postgres") ? ["postgres-data"] : []), ...(has("redis") ? ["redis-data"] : []), ...(has("s3") ? ["rustfs-data"] : []), ...(proxied ? ["caddy-data", "caddy-config"] : [])];
  return `${parts.join("\n\n")}\n\nvolumes:\n${volumes.map((v) => `  ${v}:`).join("\n")}\n`;
}
