// What a project says about how it is built and deployed: archlast-forge.json, and the files generated from it
// (compose.yaml, Dockerfile, .env, Caddyfile). Pure functions, so the CLI and the scaffolder share them.

export type Mode = "framework" | "backend";

export const MODES: Record<Mode, { label: string; hint: string }> = {
  framework: { label: "Full-stack app", hint: "React with server rendering, file routes and live queries, served by the same container as your backend" },
  backend: { label: "Backend only", hint: "A container with its database, cache and storage; use any frontend or none" },
};

export const SERVICES = {
  postgres: { label: "PostgreSQL", hint: "shared database instead of a SQLite file" },
  redis: { label: "Redis", hint: "reactivity across servers, cache and rate limits" },
  s3: { label: "S3 storage (RustFS)", hint: "file uploads with presigned URLs" },
  caddy: { label: "Caddy", hint: "HTTPS with automatic certificates in front of the app" },
} as const;
export type StackService = keyof typeof SERVICES;

/** Services a mode starts with: what a production deployment needs. An app gets HTTPS too; a backend is usually put behind a proxy of its own. */
export const DEFAULT_SERVICES: Record<Mode, StackService[]> = { framework: ["postgres", "redis", "s3", "caddy"], backend: ["postgres", "redis", "s3"] };

/** archlast-forge.json */
export interface ProjectConfig {
  mode: Mode;
  services: StackService[];
}

/** Validates archlast-forge.json with messages that say what to change. */
export function parseProjectConfig(json: unknown, source = "archlast-forge.json"): ProjectConfig {
  const bad = (why: string): never => {
    throw new Error(`${source}: ${why}`);
  };
  if (typeof json !== "object" || json === null || Array.isArray(json)) return bad("expected an object like { \"mode\": \"framework\", \"services\": [] }");
  const { mode, services = [] } = json as { mode?: unknown; services?: unknown };
  if (mode !== "framework" && mode !== "backend") return bad(`"mode" must be "framework" or "backend" (got ${JSON.stringify(mode)})`);
  if (!Array.isArray(services)) return bad(`"services" must be a list such as ["postgres", "redis"]`);
  for (const s of services) if (!(s in SERVICES)) return bad(`unknown service ${JSON.stringify(s)}; choose from ${Object.keys(SERVICES).join(", ")}`);
  return { mode, services: [...new Set(services as StackService[])] };
}

export const parseServiceList = (text: string): StackService[] => {
  const names = text.split(",").map((s) => s.trim().toLowerCase()).filter((s) => s && s !== "none");
  for (const n of names) if (!(n in SERVICES)) throw new Error(`Unknown service "${n}". Choose from ${Object.keys(SERVICES).join(", ")}, or "none".`);
  return [...new Set(names as StackService[])];
};

const hex = (bytes: number) => Buffer.from(crypto.getRandomValues(new Uint8Array(bytes))).toString("hex");

export interface Secrets {
  BETTER_AUTH_SECRET: string;
  ADMIN_KEY: string;
  POSTGRES_PASSWORD: string;
  S3_ACCESS_KEY: string;
  S3_SECRET_KEY: string;
}

export const generateSecrets = (): Secrets => ({
  BETTER_AUTH_SECRET: hex(32),
  ADMIN_KEY: hex(24),
  POSTGRES_PASSWORD: hex(16),
  S3_ACCESS_KEY: `forge${hex(6)}`,
  S3_SECRET_KEY: hex(20),
});

/** The compose file's `.env`. With no secrets it is `.env.example`: the same keys, empty. */
export function renderEnv(services: StackService[], secrets?: Secrets): string {
  const has = (s: StackService) => services.includes(s);
  const v = (k: keyof Secrets) => secrets?.[k] ?? "";
  const lines = [
    secrets ? "# Generated by archlast-forge. It holds secrets: keep it out of git." : "# Copy to .env and fill in, or let `archlast-forge up` generate one.",
    "",
    "# Signs sessions. Changing it signs everybody out.",
    `BETTER_AUTH_SECRET=${v("BETTER_AUTH_SECRET")}`,
    "# Opens the dashboard (/_dashboard) and the CLI's data commands.",
    `ADMIN_KEY=${v("ADMIN_KEY")}`,
    "",
    // DOMAIN comes first: Compose fills ${DOMAIN} only from lines above the one that uses it.
    ...(has("caddy")
      ? ["# Your domain; point its DNS (and s3.<domain>) at this machine.", "DOMAIN=localhost", "", "# The address people use to reach the app.", "BETTER_AUTH_URL=https://${DOMAIN}"]
      : ["# The address people use to reach the app.", "BETTER_AUTH_URL=http://localhost:3000", "# Plain http is only for trying things out; remove this once BETTER_AUTH_URL is https.", "ALLOW_INSECURE_HTTP=1", "PORT=3000"]),
  ];
  if (has("postgres")) lines.push("", "POSTGRES_PASSWORD=" + v("POSTGRES_PASSWORD"));
  if (has("s3")) lines.push("", `S3_ACCESS_KEY=${v("S3_ACCESS_KEY")}`, `S3_SECRET_KEY=${v("S3_SECRET_KEY")}`, "# Where browsers upload to and download from.", has("caddy") ? "S3_PUBLIC_ENDPOINT=https://s3.${DOMAIN}" : "S3_PUBLIC_ENDPOINT=http://localhost:9000");
  if (has("s3") && !has("caddy")) lines.push("# The port above is published on; change both together if 9000 is taken.", "S3_PORT=9000");
  return lines.join("\n") + "\n";
}

export function renderCaddyfile(services: StackService[]): string {
  return `# HTTPS for the app${services.includes("s3") ? " and its file storage" : ""}. Caddy gets and renews certificates by itself once DOMAIN points here.
{$DOMAIN:localhost} {
	encode zstd gzip
	reverse_proxy app:3000
}
${services.includes("s3") ? `
s3.{$DOMAIN:localhost} {
	reverse_proxy rustfs:9000
}
` : ""}`;
}

/** The engine image the project builds on; `ENGINE_IMAGE` overrides it. */
export const engineImageFor = (version: string) => `ghcr.io/algochad/archlast-forge-engine:${version}`;

export const renderDockerfile = (version: string) => `# Your app on the archlast-forge engine: \`archlast-forge build\` and \`docker compose up --build\` both use this.
ARG ENGINE_IMAGE=${engineImageFor(version)}
FROM \${ENGINE_IMAGE}
COPY . /src
# Installs dependencies for Linux, generates the types and, in a full-stack app, builds the browser and server bundles.
RUN bun /engine/packages/cli/src/index.ts engine prepare
ENV NODE_ENV=production
`;

