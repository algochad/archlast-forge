import { listModules } from "@archlast/forge-runtime/server";
import { existsSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { renderRpc, rpcRouters } from "./rpc-types";

const HEADER = "// Generated by `archlast-forge codegen`. Do not edit.\n";

type Tree = { [key: string]: Tree | string };

const render = (tree: Tree, visibility: string, indent = "  "): string =>
  Object.entries(tree)
    .map(
      ([k, v]) =>
        `${indent}${JSON.stringify(k)}: ${typeof v === "string" ? `ModuleRefs<typeof ${v}, "${visibility}">` : `{\n${render(v, visibility, indent + "  ")}${indent}}`};\n`,
    )
    .join("");

/** Writes forge/_generated/{api,dataModel}.ts, and rpc.ts when forge/ has Forge RPC routers. Types are derived from the modules, so nothing is hand-written. */
export async function codegen(forgeDir: string) {
  const modules = listModules(forgeDir);
  const tree: Tree = {};
  const imports = modules.map((m, i) => {
    const id = `m${i}_${m.name.replace(/[^a-zA-Z0-9]/g, "_")}`;
    const path = m.name.split("/");
    let node = tree;
    for (const seg of path.slice(0, -1)) node = (node[seg] ??= {}) as Tree;
    node[path.at(-1)!] = id;
    return `import type * as ${id} from "../${m.name}";\n`;
  });
  const api =
    HEADER +
    `import { anyApi, type ModuleRefs } from "@archlast/forge-runtime";\n` +
    `import type {} from "./dataModel";\n` +
    imports.join("") +
    `\n/** Public functions, callable from clients. */\nexport const api: {\n${render(tree, "public")}} = anyApi;\n` +
    `\n/** Internal functions: callable only from other functions, the scheduler and crons. */\nexport const internal: {\n${render(tree, "internal")}} = anyApi;\n`;
  const dataModel =
    HEADER +
    `import type schema from "../schema";\n\n` +
    `declare module "@archlast/forge-runtime" {\n  interface Register {\n    schema: typeof schema;\n  }\n}\n\n` +
    `export type { Doc, Id, TableNames } from "@archlast/forge-runtime";\n`;
  const out = join(forgeDir, "_generated");
  mkdirSync(out, { recursive: true });
  // Skip unchanged files so watchers don't loop.
  const write = async (file: string, content: string) => {
    const path = join(out, file);
    if (!existsSync(path) || (await Bun.file(path).text()) !== content) await Bun.write(path, content);
  };
  await write("api.ts", api);
  await write("dataModel.ts", dataModel);
  // After api.ts: the routers import it.
  const routers = await rpcRouters(forgeDir, modules);
  for (const r of routers) for (const p of r.procedures) if (p.output === null) console.warn(`! ${r.module}.ts: ${r.exportName}.${p.name} has no output schema, so callers get \`unknown\`. Add output: z.object({ ... }) to its @${p.kind === "query" ? "Query" : "Mutation"}.`);
  if (routers.length) await write("rpc.ts", renderRpc(routers, HEADER));
  else rmSync(join(out, "rpc.ts"), { force: true });
  return modules.map((m) => m.name);
}

/** Frontend code (src/ in an app with its own bundler, app/ in framework mode) may import only forge/_generated, or server-only code would reach the browser bundle. */
export async function checkFrontendImports(forgeDir: string) {
  const generated = join(forgeDir, "_generated");
  const violations: string[] = [];
  for (const dir of ["src", "app"].map((d) => join(dirname(forgeDir), d)).filter(existsSync)) {
    for (const file of new Bun.Glob("**/*.{ts,tsx,js,jsx,mts}").scanSync({ cwd: dir, absolute: true })) {
      const loader = file.endsWith("x") ? "tsx" : "ts";
      for (const imp of new Bun.Transpiler({ loader }).scanImports(await Bun.file(file).text())) {
        // Forge RPC is for calls between backends: a page never holds FORGE_RPC_TOKEN, it calls its own backend's functions.
        if (imp.path === "@archlast/forge-runtime/nest/rpc" || imp.path.startsWith("@archlast/forge-runtime/nest/rpc/")) {
          violations.push(`${relative(process.cwd(), file)} imports "${imp.path}": Forge RPC is for calls between backends (forge/ code), never from a page`);
          continue;
        }
        if (!imp.path.startsWith(".")) continue;
        const target = resolve(dirname(file), imp.path);
        const inside = (d: string) => target === d || target.startsWith(d + "/");
        if (inside(forgeDir) && !inside(generated)) violations.push(`${relative(process.cwd(), file)} imports "${imp.path}"`);
        else if (/^rpc(\.[jt]s)?$/.test(relative(generated, target))) violations.push(`${relative(process.cwd(), file)} imports "${imp.path}": Forge RPC types are for other backends, never for a page`);
      }
    }
  }
  return violations;
}
